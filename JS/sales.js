/* ==========================================================================
   Ocson Inc. Store — Point of Sale, sales history and refunds
   ========================================================================== */
(function () {
  'use strict';

  const METHODS = [
    { key: 'Cash', icon: 'banknote' }, { key: 'Mobile Money', icon: 'smartphone' }, { key: 'Bank Transfer', icon: 'landmark' }
  ];
  const Page = {
    title: 'Sales / POS',
    subtitle: 'Sell products, generate receipts and process returns',
    state: { tab: 'pos', products: [], cart: [], q: '', method: 'Cash', discount: 0, customerId: '', customers: [], sales: [], from: '', to: '', lastSale: null },

    async init() {
      this.render();
      this.bind();
      await Promise.all([this.loadProducts(), this.loadCustomers(), this.loadSales()]);
    },

    render() {
      Utils.$('#page-body').innerHTML =
        '<div class="page-heading"><div><h2>Sales desk</h2><p>Select products, apply discounts and process payments. Stock is deducted automatically.</p></div>' +
        '<div class="row"><button class="btn btn-ghost" id="sales-refresh"><i data-lucide="refresh-cw"></i> Refresh</button>' +
        '<button class="btn btn-ghost" id="sales-export"><i data-lucide="file-down"></i> Export history</button></div></div>' +
        '<div class="tabs">' +
        [['pos', 'Point of Sale', 'shopping-cart'], ['history', 'Sales history', 'receipt-text'], ['refunds', 'Refunds & returns', 'undo-2']]
          .map(([k, l, i]) => '<button class="tab' + (k === this.state.tab ? ' active' : '') + '" data-tab="' + k + '"><i data-lucide="' + i + '"></i> ' + l + '</button>').join('') +
        '</div>' +
        '<div id="sales-view"></div>';
      Utils.repaintIcons(Utils.$('#page-body'));
      this.renderTab();
    },

    bind() {
      Utils.$$('.tab').forEach((t) => t.addEventListener('click', () => {
        Utils.$$('.tab').forEach((x) => x.classList.remove('active'));
        t.classList.add('active'); this.state.tab = t.dataset.tab; this.renderTab();
      }));
      Utils.$('#sales-refresh').addEventListener('click', () => { this.loadProducts(); this.loadSales(); });
      Utils.$('#sales-export').addEventListener('click', () => this.export());
    },

    renderTab() {
      if (this.state.tab === 'pos') this.renderPOS();
      else if (this.state.tab === 'history') this.renderHistory();
      else this.renderRefunds();
    },

    /* ------------------------------- POS ---------------------------------- */
    renderPOS() {
      const v = Utils.$('#sales-view');
      v.innerHTML = '<div class="pos-layout">' +
        '<div class="card"><div class="card-header"><h3><i data-lucide="grid-2x2"></i> Products</h3>' +
        '<input class="form-control" id="pos-q" style="width:220px" placeholder="Search by name or scan SKU…"></div>' +
        '<div class="card-body"><div class="pos-product-grid" id="pos-products"></div></div></div>' +
        '<div class="card cart-panel"><div class="card-header"><h3><i data-lucide="shopping-basket"></i> Current sale</h3>' +
        '<button class="btn btn-ghost btn-sm" id="cart-clear">Clear</button></div>' +
        '<div class="card-body"><div id="cart-items"></div>' +
        '<div class="form-group mt-2"><label class="form-label">Customer</label><select class="form-select" id="pos-customer">' +
        '<option value="">Walk-in customer</option>' + this.state.customers.map((c) =>
          '<option value="' + Utils.attr(c.id) + '">' + Utils.esc(c.name) + '</option>').join('') + '</select></div>' +
        '<div class="form-row"><div class="form-group"><label class="form-label">Discount (UGX)</label>' +
        '<input class="form-control" id="pos-discount" type="number" min="0" value="0"></div>' +
        '<div class="form-group"><label class="form-label">Amount paid (optional)</label>' +
        '<input class="form-control" id="pos-paid" type="number" min="0" placeholder="0"></div></div>' +
        '<div class="form-group"><label class="form-label">Payment method</label><div class="pay-methods">' +
        METHODS.map((x) => '<button type="button" class="pay-method' + (x.key === this.state.method ? ' selected' : '') + '" data-method="' + x.key + '">' +
          '<i data-lucide="' + x.icon + '"></i>' + x.key + '</button>').join('') + '</div></div>' +
        '<div class="cart-totals" id="cart-totals"></div>' +
        '<button class="btn btn-primary btn-lg btn-block" id="cart-checkout"><i data-lucide="check-circle-2"></i> Complete sale</button>' +
        '<p class="form-hint text-center mt-2">A unique receipt number is generated by the server.</p>' +
        '</div></div></div>';
      Utils.repaintIcons(v);
      Utils.$('#pos-q').addEventListener('input', Utils.debounce((e) => { this.state.q = e.target.value; this.renderProducts(); }, 200));
      Utils.$$('.pay-method').forEach((b) => b.addEventListener('click', () => {
        this.state.method = b.dataset.method;
        Utils.$$('.pay-method').forEach((x) => x.classList.toggle('selected', x === b));
      }));
      Utils.$('#cart-clear').addEventListener('click', () => { this.state.cart = []; this.renderCart(); });
      Utils.$('#pos-discount').addEventListener('input', (e) => { this.state.discount = Number(e.target.value) || 0; this.renderCart(); });
      Utils.$('#cart-checkout').addEventListener('click', () => this.checkout());
      this.renderProducts();
      this.renderCart();
    },

    renderProducts() {
      const grid = Utils.$('#pos-products');
      if (!grid) return;
      const q = this.state.q.toLowerCase();
      const list = this.state.products.filter((p) =>
        !q || (p.name + ' ' + (p.sku || '')).toLowerCase().includes(q));
      grid.innerHTML = list.length ? list.slice(0, 60).map((p) =>
        '<button class="pos-product" data-id="' + Utils.attr(p.id) + '"' + (Number(p.stock) <= 0 ? ' disabled style="opacity:.5"' : '') + '>' +
        (p.imageUrl ? '<img src="' + Utils.attr(p.imageUrl) + '" alt="" loading="lazy">' :
          '<div style="height:88px;border-radius:8px;background:var(--surface-3);display:grid;place-items:center;font-size:28px;font-weight:800;color:var(--muted);margin-bottom:9px">' + Utils.esc(String(p.name).charAt(0)) + '</div>') +
        '<span class="stock">' + Utils.number(p.stock) + ' left</span>' +
        '<div class="name">' + Utils.esc(p.name) + '</div><div class="sku">' + Utils.esc(p.sku || '') + '</div>' +
        '<div class="price">' + Utils.money(p.sellingPrice) + '</div></button>').join('') :
        Utils.emptyState('No products found', 'Try another search term or refresh the catalogue.');
      Utils.$$('.pos-product').forEach((b) => b.addEventListener('click', () => this.addToCart(b.dataset.id)));
      Utils.repaintIcons(grid);
    },

    addToCart(id) {
      const p = this.state.products.find((x) => String(x.id) === String(id));
      if (!p) return;
      if (Number(p.stock) <= 0) { Utils.toast(p.name + ' is out of stock', 'warning'); return; }
      const line = this.state.cart.find((x) => String(x.id) === String(id));
      if (line) {
        if (line.qty >= Number(p.stock)) { Utils.toast('No more stock available for ' + p.name, 'warning'); return; }
        line.qty++;
      } else this.state.cart.push({ id: p.id, name: p.name, price: Number(p.sellingPrice), qty: 1, stock: Number(p.stock), sku: p.sku });
      this.renderCart();
    },

    renderCart() {
      const box = Utils.$('#cart-items'), totals = Utils.$('#cart-totals');
      if (!box || !totals) return;
      if (!this.state.cart.length) {
        box.innerHTML = '<div class="cart-empty"><i data-lucide="shopping-basket"></i><p>Your cart is empty.<br>Select a product to begin.</p></div>';
      } else {
        box.innerHTML = this.state.cart.map((l) =>
          '<div class="cart-item"><div class="cart-item-info"><div class="cart-item-name">' + Utils.esc(l.name) + '</div>' +
          '<div class="cart-item-price">' + Utils.money(l.price) + ' each</div>' +
          '<div class="qty-control mt-1"><button data-q="dec" data-id="' + Utils.attr(l.id) + '">−</button>' +
          '<input value="' + l.qty + '" data-qty-input="' + Utils.attr(l.id) + '" min="1" max="' + l.stock + '">' +
          '<button data-q="inc" data-id="' + Utils.attr(l.id) + '">+</button></div></div>' +
          '<div class="text-right"><strong>' + Utils.money(l.price * l.qty) + '</strong>' +
          '<button class="btn btn-ghost btn-sm btn-icon" data-q="remove" data-id="' + Utils.attr(l.id) + '"><i data-lucide="trash-2"></i></button></div></div>').join('');
        Utils.$$('[data-q]').forEach((b) => b.addEventListener('click', () => this.cartAction(b.dataset.q, b.dataset.id)));
        Utils.$$('[data-qty-input]').forEach((i) => i.addEventListener('change', () => {
          const line = this.state.cart.find((x) => String(x.id) === String(i.dataset.qtyInput));
          if (!line) return;
          const n = Math.max(1, Math.min(line.stock, parseInt(i.value, 10) || 1));
          line.qty = n; this.renderCart();
        }));
      }
      const sub = Utils.sum(this.state.cart, (l) => l.price * l.qty);
      const disc = Math.min(this.state.discount, sub);
      const total = Math.max(0, sub - disc);
      totals.innerHTML =
        '<div class="total-line"><span>Subtotal</span><strong>' + Utils.money(sub) + '</strong></div>' +
        '<div class="total-line"><span>Discount</span><strong>− ' + Utils.money(disc) + '</strong></div>' +
        '<div class="total-line"><span>Items</span><strong>' + Utils.sum(this.state.cart, (l) => l.qty) + '</strong></div>' +
        '<div class="total-line grand"><span>Total</span><span>' + Utils.money(total) + '</span></div>';
      Utils.repaintIcons(box);
    },

    cartAction(action, id) {
      const idx = this.state.cart.findIndex((x) => String(x.id) === String(id));
      if (idx < 0) return;
      if (action === 'inc' && this.state.cart[idx].qty < this.state.cart[idx].stock) this.state.cart[idx].qty++;
      if (action === 'dec') { this.state.cart[idx].qty--; if (this.state.cart[idx].qty <= 0) this.state.cart.splice(idx, 1); }
      if (action === 'remove') this.state.cart.splice(idx, 1);
      this.renderCart();
    },

    async checkout() {
      if (!this.state.cart.length) { Utils.toast('Add at least one product to the cart', 'warning'); return; }
      const ok = await Utils.confirm('Complete sale', 'Post this sale, deduct stock and generate a receipt?', { confirmText: 'Process payment' });
      if (!ok) return;
      try {
        const res = await API.createSale({
          items: this.state.cart.map((l) => ({ productId: l.id, quantity: l.qty })),
          discount: this.state.discount,
          paymentMethod: this.state.method,
          customerId: Utils.$('#pos-customer')?.value || '',
          amountPaid: Number(Utils.$('#pos-paid')?.value) || 0,
          requestId: Utils.FN_id()
        }, { loading: true, loadingLabel: 'Processing sale & updating stock…' });
        this.state.cart = []; this.state.discount = 0;
        const paid = Number(Utils.$('#pos-paid')?.value) || 0;
        if (Utils.$('#pos-paid')) Utils.$('#pos-paid').value = '';
        if (Utils.$('#pos-discount')) Utils.$('#pos-discount').value = '0';
        Utils.toast('Sale completed · ' + (res.sale?.receiptNo || res.receiptNo || ''), 'success');
        await Promise.all([this.loadProducts(), this.loadSales(), this.loadCustomers()]);
        this.renderCart();
        this.receipt(res.sale || res, paid);
      } catch (e) { Utils.toast(e.message, 'error'); }
    },

    receipt(sale, paid) {
      if (!sale) return;
      const items = (sale.items || []).map((i) =>
        '<tr><td>' + Utils.esc(i.productName || i.name || i.productId) + '</td><td class="text-right">' + Utils.number(i.quantity) +
        ' × ' + Utils.money(i.unitPrice) + '</td><td class="text-right">' + Utils.money(i.lineTotal != null ? i.lineTotal : Number(i.quantity) * Number(i.unitPrice)) + '</td></tr>').join('');
      const html = '<div class="receipt" id="receipt-print"><h2>' + APP_CONFIG.APP_NAME.toUpperCase() + '</h2>' +
        '<div class="receipt-sub">Tax invoice / receipt · Thank you for shopping with us</div>' +
        '<div class="hr"></div>' +
        '<div>Receipt: <strong>' + Utils.esc(sale.receiptNo || '') + '</strong></div>' +
        '<div>Transaction: ' + Utils.esc(sale.id || '') + '</div>' +
        '<div>Date: ' + Utils.datetime(sale.date || new Date()) + '</div>' +
        '<div>Customer: ' + Utils.esc(sale.customerName || 'Walk-in') + '</div>' +
        '<div>Method: ' + Utils.esc(sale.paymentMethod || sale.method || '') + '</div>' +
        '<div class="hr"></div><table><thead><tr><th>Item</th><th class="text-right">Qty × Price</th><th class="text-right">Amount</th></tr></thead><tbody>' +
        items + '</tbody></table><div class="hr"></div>' +
        '<table><tr><td>Subtotal</td><td class="text-right">' + Utils.money(sale.subtotal) + '</td></tr>' +
        '<tr><td>Discount</td><td class="text-right">− ' + Utils.money(sale.discount) + '</td></tr>' +
        '<tr class="total"><td>TOTAL</td><td class="text-right">' + Utils.money(sale.total) + '</td></tr>' +
        (paid ? '<tr><td>Paid</td><td class="text-right">' + Utils.money(paid) + '</td></tr><tr><td>Change</td><td class="text-right">' + Utils.money(paid - Number(sale.total)) + '</td></tr>' : '') +
        '</table><div class="hr"></div><p class="text-center">Goods sold are not returnable without receipt.<br>Generated by ' + APP_CONFIG.APP_NAME + '</p></div>';
      const m = Utils.modal({
        title: 'Sale complete', icon: 'circle-check-big', size: 'md',
        body: '<div class="alert alert-success" style="display:block"><strong>Stock updated successfully.</strong> Receipt ' +
          Utils.esc(sale.receiptNo || '') + ' has been saved.</div>' + html,
        footer: '<button class="btn btn-ghost" id="receipt-print-btn"><i data-lucide="printer"></i> Print</button>' +
          '<button class="btn btn-primary" id="receipt-pdf-btn"><i data-lucide="file-down"></i> Download PDF</button>',
        showConfirm: false, cancelText: 'Close'
      });
      Utils.repaintIcons(m.el);
      Utils.$('#receipt-print-btn', m.el).addEventListener('click', () => Utils.printHTML(Utils.$('#receipt-print', m.el).outerHTML, 'Receipt ' + (sale.receiptNo || '')));
      Utils.$('#receipt-pdf-btn', m.el).addEventListener('click', () => {
        const { jsPDF } = window.jspdf;
        const doc = new jsPDF({ unit: 'mm', format: [80, 200] });
        doc.setFont('courier', 'bold'); doc.setFontSize(13); doc.text(APP_CONFIG.APP_NAME.toUpperCase(), 40, 12, { align: 'center' });
        doc.setFontSize(8); doc.text('RECEIPT ' + (sale.receiptNo || ''), 40, 19, { align: 'center' });
        doc.text(Utils.datetime(sale.date || new Date()), 40, 25, { align: 'center' });
        doc.line(5, 30, 75, 30);
        let y = 38;
        (sale.items || []).forEach((i) => {
          doc.text(String(i.productName || i.name || '').slice(0, 24), 5, y);
          doc.text(Utils.number(i.quantity) + 'x' + Utils.number(i.unitPrice), 5, y + 4);
          doc.text(Utils.money(i.lineTotal != null ? i.lineTotal : Number(i.quantity) * Number(i.unitPrice)), 75, y, { align: 'right' });
          y += 10;
        });
        doc.line(5, y, 75, y); y += 7;
        doc.setFont('courier', 'bold'); doc.text('TOTAL', 5, y); doc.text(Utils.money(sale.total), 75, y, { align: 'right' });
        y += 8; doc.setFont('courier', 'normal'); doc.text('Thank you for shopping with us', 40, y + 6, { align: 'center' });
        doc.save('receipt_' + (sale.receiptNo || sale.id) + '.pdf');
      });
    },

    /* --------------------------- Sales history ---------------------------- */
    async loadSales() {
      try {
        const res = await API.sales({ from: this.state.from, to: this.state.to, limit: 200 });
        this.state.sales = Array.isArray(res) ? res : (res.items || []);
      } catch (e) { this.state.sales = []; }
      if (this.state.tab !== 'pos') this.renderTab();
    },
    async loadProducts() {
      try {
        const res = await API.products({ status: 'Active' });
        this.state.products = Array.isArray(res) ? res : (res.items || []);
      } catch (e) { Utils.toast(e.message, 'error'); }
      if (this.state.tab === 'pos') this.renderProducts();
    },
    async loadCustomers() {
      try {
        const res = await API.customers({ limit: 500 });
        this.state.customers = Array.isArray(res) ? res : (res.items || []);
      } catch (_) {}
    },

    renderHistory() {
      const v = Utils.$('#sales-view');
      const rows = this.state.sales.filter((s) => String(s.status || 'Completed').toLowerCase() !== 'refunded');
      v.innerHTML = '<div class="card"><div class="card-header"><h3><i data-lucide="receipt-text"></i> Sales history</h3>' +
        '<div class="date-range"><input type="date" id="sh-from" class="form-control" value="' + Utils.attr(this.state.from) + '">' +
        '<span class="muted">to</span><input type="date" id="sh-to" class="form-control" value="' + Utils.attr(this.state.to) + '">' +
        '<button class="btn btn-primary btn-sm" id="sh-apply"><i data-lucide="filter"></i> Filter</button></div></div>' +
        '<div class="card-body">' + Utils.table([
          { label: 'Receipt', key: 'receiptNo', render: (s) => '<strong>' + Utils.esc(s.receiptNo || s.id) + '</strong>' },
          { label: 'Date', key: 'date', render: (s) => Utils.datetime(s.date) },
          { label: 'Customer', key: 'customerName', render: (s) => Utils.esc(s.customerName || 'Walk-in') },
          { label: 'Method', key: 'paymentMethod', render: (s) => Utils.badge(s.paymentMethod || s.method) },
          { label: 'Subtotal', key: 'subtotal', align: 'right', render: (s) => Utils.money(s.subtotal) },
          { label: 'Discount', key: 'discount', align: 'right', render: (s) => '− ' + Utils.money(s.discount) },
          { label: 'Total', key: 'total', align: 'right', render: (s) => '<strong>' + Utils.money(s.total) + '</strong>' },
          { label: 'Status', key: 'status', render: (s) => Utils.statusBadge(s.status || 'Completed') },
          { label: 'Actions', align: 'right', render: (s) => '<div class="action-group">' +
            '<button class="btn btn-ghost btn-sm btn-icon" data-sale="view" data-id="' + Utils.attr(s.id) + '"><i data-lucide="eye"></i></button>' +
            '<button class="btn btn-ghost btn-sm btn-icon" data-sale="receipt" data-id="' + Utils.attr(s.id) + '"><i data-lucide="printer"></i></button>' +
            (Auth.can('sales.refund') && String(s.status || '').toLowerCase() !== 'refunded' ?
              '<button class="btn btn-ghost btn-sm btn-icon" data-sale="refund" data-id="' + Utils.attr(s.id) + '"><i data-lucide="undo-2"></i></button>' : '') + '</div>' }
        ], rows, { empty: 'No sales recorded for this period.' }) + '</div></div>';
      Utils.repaintIcons(v);
      Utils.$('#sh-apply').addEventListener('click', () => { this.state.from = Utils.$('#sh-from').value; this.state.to = Utils.$('#sh-to').value; this.loadSales(); });
      Utils.$$('[data-sale]').forEach((b) => b.addEventListener('click', () => {
        const s = this.state.sales.find((x) => String(x.id) === String(b.dataset.id));
        if (b.dataset.sale === 'view') this.viewSale(s);
        if (b.dataset.sale === 'receipt') this.receipt(s);
        if (b.dataset.sale === 'refund') this.refund(s);
      }));
    },

    async viewSale(s) {
      if (!s) return;
      let items = s.items || [];
      try { const res = await API.saleItems(s.id); if (Array.isArray(res)) items = res; else if (res?.items) items = res.items; } catch (_) {}
      Utils.modal({
        title: 'Sale ' + (s.receiptNo || s.id), icon: 'receipt-text', size: 'lg', showConfirm: false, cancelText: 'Close',
        body: '<div class="kv-grid mb-3">' +
          '<div class="kv-item"><span class="kv-label">Date</span><span class="kv-value">' + Utils.datetime(s.date) + '</span></div>' +
          '<div class="kv-item"><span class="kv-label">Customer</span><span class="kv-value">' + Utils.esc(s.customerName || 'Walk-in') + '</span></div>' +
          '<div class="kv-item"><span class="kv-label">Payment method</span><span class="kv-value">' + Utils.esc(s.paymentMethod || '') + '</span></div>' +
          '<div class="kv-item"><span class="kv-label">Salesperson</span><span class="kv-value">' + Utils.esc(s.user || '') + '</span></div>' +
          '<div class="kv-item"><span class="kv-label">Subtotal</span><span class="kv-value">' + Utils.money(s.subtotal) + '</span></div>' +
          '<div class="kv-item"><span class="kv-label">Discount</span><span class="kv-value">' + Utils.money(s.discount) + '</span></div>' +
          '</div>' + Utils.table([
            { label: 'Product', key: 'productName', render: (i) => Utils.esc(i.productName || i.name || i.productId) },
            { label: 'Quantity', key: 'quantity', align: 'right' },
            { label: 'Unit price', key: 'unitPrice', align: 'right', render: (i) => Utils.money(i.unitPrice) },
            { label: 'Line total', key: 'lineTotal', align: 'right', render: (i) => Utils.money(i.lineTotal != null ? i.lineTotal : Number(i.quantity) * Number(i.unitPrice)) }
          ], items, { empty: 'Line items are not available for this sale.' }) +
          '<div class="total-line grand mt-2"><span>Grand total</span><span>' + Utils.money(s.total) + '</span></div>'
      });
    },

    renderRefunds() {
      const rows = this.state.sales.filter((s) => String(s.status || '').toLowerCase() === 'refunded' || Number(s.refunded) > 0);
      const v = Utils.$('#sales-view');
      v.innerHTML = '<div class="alert alert-info"><i data-lucide="info"></i><div>Refunds restore the returned quantities to stock and are recorded in the Returns sheet. Open a sale from <strong>Sales history</strong> to issue a refund.</div></div>' +
        '<div class="card"><div class="card-header"><h3><i data-lucide="undo-2"></i> Refunded transactions</h3></div><div class="card-body">' +
        Utils.table([
          { label: 'Receipt', key: 'receiptNo', render: (s) => Utils.esc(s.receiptNo || s.id) },
          { label: 'Date', key: 'date', render: (s) => Utils.datetime(s.date) },
          { label: 'Customer', key: 'customerName', render: (s) => Utils.esc(s.customerName || 'Walk-in') },
          { label: 'Original total', key: 'total', align: 'right', render: (s) => Utils.money(s.total) },
          { label: 'Refunded', key: 'refunded', align: 'right', render: (s) => Utils.money(s.refunded || s.total) },
          { label: 'Status', key: 'status', render: (s) => Utils.badge('Refunded', 'danger') }
        ], rows, { empty: 'No refunds have been recorded.' }) + '</div></div>';
      Utils.repaintIcons(v);
    },

    async refund(s) {
      if (!s) return;
      const m = Utils.modal({
        title: 'Refund sale ' + (s.receiptNo || s.id), icon: 'undo-2', danger: true, size: 'md', confirmText: 'Issue refund',
        body: '<form id="refund-form"><div class="alert alert-warning"><i data-lucide="triangle-alert"></i><div>This will restore sold quantities to stock and record a refund of up to <strong>' +
          Utils.money(s.total) + '</strong>.</div></div>' +
          '<div class="form-group"><label class="form-label">Refund amount (UGX)</label><input class="form-control" name="amount" type="number" min="0" max="' + Number(s.total) + '" value="' + Number(s.total) + '" required></div>' +
          '<div class="form-group"><label class="form-label">Reason <span class="req">*</span></label><textarea class="form-control" name="reason" required placeholder="e.g. Customer returned damaged item"></textarea></div></form>',
        onConfirm: async (el) => {
          const form = Utils.$('#refund-form', el), data = Utils.formData(form);
          const v = Utils.validate(data, { amount: { required: true, numeric: true, minValue: 1 }, reason: { required: true, min: 3 } });
          if (!v.ok) { Utils.showFormErrors(form, v.errors); return false; }
          if (Number(data.amount) > Number(s.total)) { Utils.showFormErrors(form, { amount: 'Cannot exceed sale total' }); return false; }
          const sure = await Utils.confirm('Confirm refund', 'Refund ' + Utils.money(data.amount) + ' for receipt ' + (s.receiptNo || s.id) + '?', { danger: true, confirmText: 'Yes, refund' });
          if (!sure) return false;
          await API.refundSale(Object.assign({ saleId: s.id, requestId: Utils.FN_id() }, data));
          Utils.toast('Refund recorded and stock restored', 'success');
          this.loadSales(); this.loadProducts();
          return true;
        }
      });
      return m;
    },

    export() {
      Utils.exportCSV('sales', this.state.sales, [
        { label: 'Transaction ID', key: 'id' }, { label: 'Receipt No', key: 'receiptNo' }, { label: 'Date', key: 'date' },
        { label: 'Customer', key: 'customerName' }, { label: 'Payment Method', key: 'paymentMethod' },
        { label: 'Subtotal', key: 'subtotal' }, { label: 'Discount', key: 'discount' }, { label: 'Total', key: 'total' },
        { label: 'Cost', key: 'cogs' }, { label: 'Status', key: 'status' }, { label: 'User', key: 'user' }
      ]);
    }
  };

  window.Page = Page;
})();
